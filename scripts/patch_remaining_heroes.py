def main():
    if not SKILLS_JSON.exists():
        raise FileNotFoundError(f"{SKILLS_JSON} not found!")

    with open(SKILLS_JSON, "r", encoding="utf-8") as f:
        catalog = json.load(f)

    heroes = catalog["heroes"]
    total_updated = 0

    for hero_name, skills in PATCHED_HEROES.items():
        heroes[hero_name] = skills
        total_updated += 1

    catalog["total_skills"] = sum(len(s) for s in heroes.values())

    with open(SKILLS_JSON, "w", encoding="utf-8") as f:
        json.dump(catalog, f, indent=2, ensure_ascii=False)
    print(f"Updated {total_updated} heroes in {SKILLS_JSON}")

    with open(HEROES_JSON, "r", encoding="utf-8") as f:
        h130 = json.load(f)
    for h in h130:
        if h["name"] in PATCHED_HEROES:
            h["skills"] = PATCHED_HEROES[h["name"]]

    with open(HEROES_JSON, "w", encoding="utf-8") as f:
        json.dump(h130, f, indent=2, ensure_ascii=False)
    print(f"Synced {total_updated} heroes to {HEROES_JSON}")


if __name__ == "__main__":
    main()
